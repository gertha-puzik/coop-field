def build(map_str: str, pal: dict, name: str, ox=24, oy=112):
    rows = [r for r in map_str.strip('\n').split('\n')]
    w = max(len(r) for r in rows)
    h = len(rows)
    im = Image.new('RGBA', (100, 150), (0, 0, 0, 0))
    px = im.load()
    for j, row in enumerate(rows):
        for i, ch in enumerate(row):
            c = pal.get(ch)
            if c is None:
                continue
            x, y = ox + i, oy + j
            if 0 <= x < 100 and 0 <= y < 150:
                px[x, y] = c
    im.save(f'public/sprites/{name}.png')
    print(name, 'ok, bbox:', im.getchannel('A').getbbox())

