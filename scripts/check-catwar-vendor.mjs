const problems = [];
const fail = (msg) => problems.push(msg);

/** Рекурсивный обход копии: [{rel, abs}] — сравниваем и состав, и sha. */
function walkVendor(dir, out = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walkVendor(p, out);
    else if (ent.isFile()) out.push({ rel: path.relative(VENDOR, p), abs: p });
  }
  return out;
}

const onDisk = walkVendor(VENDOR);
const canon = new Set(Object.keys(VENDOR_SHA256));
const disk = new Set(onDisk.map((f) => f.rel));

for (const rel of [...canon].sort()) {
  if (!disk.has(rel)) fail(`нет файла ${rel} (канон ждёт его в public/catwar)`);
}
for (const file of onDisk) {
  if (!canon.has(file.rel)) fail(`лишний файл public/catwar/${file.rel} — его нет в каноне`);
}
for (const file of onDisk) {
  const want = VENDOR_SHA256[file.rel];
  if (!want) continue;
  const sha = createHash("sha256").update(fs.readFileSync(file.abs)).digest("hex");
  if (sha !== want) fail(`${file.rel}: sha256 ${sha} != эталон ${want} — копию правили (или синхронизировали kns: обнови таблицу осознанным PR)`);
}

if (problems.length) {
  console.error(`check-catwar-vendor: ПРОВАЛ (${problems.length})`);
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}
console.log(`check-catwar-vendor: OK — ${onDisk.length} файлов копии == канон (tint.js + манифест + gray/{norm,thin,chub} + tint_meta.json)`);
